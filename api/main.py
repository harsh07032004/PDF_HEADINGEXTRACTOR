# ── Global exception handlers ──────────────────────────────────────────────────

@app.exception_handler(404)
async def not_found_handler(_req: object, _exc: object) -> JSONResponse:
    return JSONResponse(status_code=404, content={"error": "Not found", "status_code": 404})


@app.exception_handler(500)
async def server_error_handler(_req: object, exc: Exception) -> JSONResponse:
    log.exception("Unhandled server error")
    return JSONResponse(
        status_code=500,
        content={"error": "Internal server error", "detail": str(exc), "status_code": 500},
    )
