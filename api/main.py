# ── Helper: convert engine output → API response ───────────────────────────────

def _outline_to_response(outline: DocumentOutline, min_confidence: float) -> ExtractResponse:
    """Convert a DocumentOutline dataclass into an ExtractResponse Pydantic model."""
    heading_responses = [
        HeadingResponse(
            level=h.level,
            text=h.text,
            page=h.page,
            confidence=h.confidence,
            font_name=h.font_name,
            font_size=h.font_size,
            bounding_box=BoundingBoxResponse(
                x0=h.bounding_box.x0,
                y0=h.bounding_box.y0,
                x1=h.bounding_box.x1,
                y1=h.bounding_box.y1,
            ),
            confidence_label=describe_confidence(h.confidence),
        )
        for h in outline.headings
        if h.confidence >= min_confidence
    ]

    meta = ExtractionMetadataResponse(
        filename=outline.filename,
        total_pages=outline.total_pages,
        language=outline.metadata.language,
        toc_available=outline.metadata.toc_available,
        scanned_pdf_detected=outline.metadata.scanned_pdf_detected,
        processing_time_ms=outline.metadata.processing_time_ms,
        engine_version=outline.metadata.engine_version,
    )

    return ExtractResponse(
        title=outline.title,
        outline=heading_responses,
        metadata=meta,
    )


async def _save_upload_to_temp(upload: UploadFile) -> Path:
    """
    Save an UploadFile to a temporary file and return its Path.

    Enforces the MAX_FILE_SIZE_BYTES limit by counting bytes as we stream.
    Raises HTTPException(413) if exceeded.
    """
    suffix = Path(upload.filename or "upload.pdf").suffix or ".pdf"
    tmp = tempfile.NamedTemporaryFile(delete=False, suffix=suffix)
    tmp_path = Path(tmp.name)
    total = 0

    try:
        while chunk := await upload.read(65536):
            total += len(chunk)
            if total > MAX_FILE_SIZE_BYTES:
                tmp.close()
                tmp_path.unlink(missing_ok=True)
                raise HTTPException(
                    status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
                    detail=f"File exceeds the {MAX_FILE_SIZE_MB} MB limit.",
                )
            tmp.write(chunk)
    finally:
        tmp.close()

    return tmp_path


