@app.post(
    "/extract",
    response_model=ExtractResponse,
    summary="Extract headings from a single PDF",
    tags=["Extraction"],
    responses={
        400: {"model": ErrorResponse, "description": "Invalid file or parameters"},
        413: {"model": ErrorResponse, "description": "File too large"},
        422: {"model": ErrorResponse, "description": "Validation error"},
        500: {"model": ErrorResponse, "description": "Extraction error"},
    },
)
async def extract(
    file: UploadFile = File(..., description="PDF file to process."),
    lang: str = Query(default="en", description="Language code (en, es, fr, de, ja)."),
    min_confidence: float = Query(
        default=0.45, ge=0.0, le=1.0,
        description="Minimum confidence threshold (0.0–1.0).",
    ),
    use_ml: bool = Query(
        default=True, description="Use the trained ML model for heading classification."
    ),
) -> ExtractResponse:
    """
    Upload a PDF file and receive its heading structure.

    The response contains:
    - **title**: detected document title
    - **outline**: list of headings with level (H1/H2/H3), page, confidence,
      font metadata, and bounding box coordinates
    - **metadata**: processing stats (timing, TOC availability, scanned detection)
    """
    if lang not in SUPPORTED_LANGUAGES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Unsupported language '{lang}'. Choose from: {SUPPORTED_LANGUAGES}",
        )

    tmp_path = await _save_upload_to_temp(file)

    try:
        if not is_valid_pdf(tmp_path):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Uploaded file does not appear to be a valid PDF.",
            )

        log.info("Extracting: %s  lang=%s", file.filename, lang)

        with ExtractorEngine(tmp_path, lang=lang, use_ml=use_ml) as engine:
            outline = engine.process()

        if outline.metadata.scanned_pdf_detected:
            log.warning("Scanned PDF detected: %s", file.filename)

        return _outline_to_response(outline, min_confidence)

    except HTTPException:
        raise
    except Exception as exc:
        log.exception("Extraction failed for %s", file.filename)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Extraction failed: {exc}",
        ) from exc
    finally:
        tmp_path.unlink(missing_ok=True)


@app.post(
    "/extract/batch",
    response_model=BatchExtractResponse,
    summary="Extract headings from multiple PDFs",
    tags=["Extraction"],
)
async def extract_batch(
    files: list[UploadFile] = File(..., description="PDF files to process (max 10)."),
    lang: str = Query(default="en", description="Language code applied to all files."),
    min_confidence: float = Query(default=0.45, ge=0.0, le=1.0),
    use_ml: bool = Query(default=True),
) -> BatchExtractResponse:
    """
    Upload up to 10 PDF files and receive heading structures for all of them.

    Files are processed sequentially. Failed files are reported in the
    ``failed`` count without aborting the rest of the batch.
    """
    if len(files) > 10:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Batch endpoint accepts a maximum of 10 files per request.",
        )

    if lang not in SUPPORTED_LANGUAGES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Unsupported language '{lang}'.",
        )

    batch_start = time.perf_counter()
    results: list[ExtractResponse] = []
    failed = 0

    for upload in files:
        tmp_path = await _save_upload_to_temp(upload)
        try:
            if not is_valid_pdf(tmp_path):
                log.warning("Skipping non-PDF: %s", upload.filename)
                failed += 1
                continue

            with ExtractorEngine(tmp_path, lang=lang, use_ml=use_ml) as engine:
                outline = engine.process()

            results.append(_outline_to_response(outline, min_confidence))
            log.info("Batch item OK: %s", upload.filename)

        except Exception as exc:
            log.error("Batch item failed (%s): %s", upload.filename, exc)
            failed += 1
        finally:
            tmp_path.unlink(missing_ok=True)

    total_ms = round((time.perf_counter() - batch_start) * 1000, 2)

    return BatchExtractResponse(
        results=results,
        total_files=len(files),
        successful=len(results),
        failed=failed,
        total_processing_time_ms=total_ms,
    )


# ── Global exception handlers ──────────────────────────────────────────────────

@app.exception_handler(404)
async def not_found_handler(_req: object, _exc: object) -> JSONResponse:
    return JSONResponse(
        status_code=404,
        content={"error": "Not found", "status_code": 404},
    )


@app.exception_handler(500)
async def server_error_handler(_req: object, exc: Exception) -> JSONResponse:
    log.exception("Unhandled server error")
    return JSONResponse(
        status_code=500,
        content={"error": "Internal server error", "detail": str(exc), "status_code": 500},
    )
